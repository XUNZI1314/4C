from pathlib import Path
import sys

import streamlit as st

ROOT_DIR = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT_DIR / "src"
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from protein_visualizer.config.settings import SETTINGS

st.set_page_config(page_title=f"{SETTINGS.page_title} - 使用说明", layout="wide")

st.title("使用说明")

st.markdown(
    """
    ## 1. 推荐分析链路
    1. 在“结构可视化”页面上传 PDB，并选择能量来源：自动、上传 MMPBSA 或结构估算。
    2. 检查三维结构、颜色模式、热点阈值和残基能量明细，确认基础结构映射可信。
    3. 在“口袋与界面”页面运行自动口袋识别，并按需要加入 UniProt、M-CSA、文献、AI 提取残基、保守性表格或人工关键残基。
    4. 使用文献 A/B、证据路径 A/B、保守性 A/B 和 P2Rank on/off 对照，判断证据是否真的提升关键口袋排序。
    5. 在“多构象比较”页面检查热点稳定性，避免只依赖单一构象得出结论。
    6. 在“结果与导出”页面导出 CSV、JSON 快照、SVG 快照、文本报告和 PDF 报告。

    ## 2. 输入数据
    - **PDB 文件**：蛋白质三维结构，是所有分析的基础。
    - **MMPBSA 输出文件**：包含 residue-level `DELTA TOTAL` 时，可用于残基能量热力映射。
    - **Pocket 文件**：可上传已有口袋 CSV，也可以不上传并使用自动口袋识别。
    - **界面注释文件**：可上传蛋白-蛋白或蛋白-配体界面残基；未上传时系统可尝试结构推断。
    - **外部证据**：支持 UniProt、M-CSA、文献残基、AI 辅助提取结果、保守性表格和人工关键残基。

    ## 3. 结构可视化
    - **卡通视图**：适合观察整体折叠和二级结构。
    - **球棍视图**：适合观察局部原子结构和关键残基。
    - **分子表面**：适合观察口袋开口、表面包络和残基暴露程度。
    - 颜色可按 `DELTA TOTAL` 热度、理化性质、电荷、极性、热点等级、口袋识别结果或链编号切换。

    ## 4. 口袋与证据复核
    - 自动口袋识别会综合几何聚类、热点残基、配体邻近关系、外部功能证据和可选的 P2Rank / pyKVFinder 结果。
    - 对酶蛋白，优先关注围绕催化残基、底物/辅因子结合残基、金属配位残基或高置信文献残基形成的口袋。
    - AI 残基证据需要来源文本、片段或引用支持；冲突、无来源或低置信证据会进入复核队列，不应直接作为高置信结论。
    - 保守性证据适合作为重排信号，但不应单独替代结构口袋和文献功能证据。

    ## 5. 多构象比较
    - 上传多个 PDB 时，可以比较不同构象的热点集合、稳定热点、可变热点和成对相似度。
    - 若关键热点只在单一构象出现，应回到结构和证据页复核构象来源、能量来源和口袋边界。

    ## 6. 结果导出与历史
    - “结果与导出”页面可以导出残基注释、智能口袋摘要、联合推荐、快照和报告。
    - “分析历史”会记录平均能量、蛋白体积、热点数、口袋数、Top1 口袋证据质量和自动口袋方法。
    - 导出的 CSV 保留原始字段，页面显示会尽量使用中文列名，便于继续分析和人工复核。

    ## 7. 注意事项
    - MMPBSA 文件需包含可解析的 `DELTA TOTAL`；格式不标准时可能需要扩展解析器。
    - 结构估算模式只用于没有 MMPBSA 文件时的近似分析，不等同于真实 MMPBSA 结果。
    - 文献或 UniProt 残基编号可能与 PDB author numbering、插入码或成熟肽编号不一致，关键结论前必须检查残基映射。
    - 大型 PDB 文件和复杂表面渲染会增加浏览器压力，可优先使用卡通视图或降低显示复杂度。
    """
)

def test_precision_residue_table_prefers_structure_verified_external_alignment():
    atom_df = parse_pdb_atoms(PDB_TEXT)
    external_site_df = pd.DataFrame(
        [
            {
                "chain": "A",
                "resid": 1,
                "evidence_source": "UniProt+SIFTS",
                "evidence_type": "Active site",
                "evidence_score": 0.95,
                "mapping_level": "exact",
                "mapping_confidence": 0.96,
                "mapping_method": "sifts-structure-order",
            },
            {
                "chain": "A",
                "resid": 2,
                "evidence_source": "UniProt+SIFTS",
                "evidence_type": "Active site",
                "evidence_score": 0.95,
                "mapping_level": "weak",
                "mapping_confidence": 0.58,
                "mapping_method": "sifts-gap-fallback",
            },
        ]
    )

    residue_df, _ligand_atoms = _build_precision_residue_table(
        atom_df,
        set(),
        pdb_text=PDB_TEXT,
        contact_cutoff=7.2,
        ligand_radius=4.5,
        external_site_df=external_site_df,
    )

    verified_row = residue_df[(residue_df["chain"].astype(str) == "A") & (residue_df["resid"].astype(int) == 1)].iloc[0]
    fallback_row = residue_df[(residue_df["chain"].astype(str) == "A") & (residue_df["resid"].astype(int) == 2)].iloc[0]

    assert bool(verified_row["external_structure_verified"]) is True
    assert float(verified_row["external_mapping_quality"]) > float(fallback_row["external_mapping_quality"])
    assert float(verified_row["external_support"]) > float(fallback_row["external_support"])



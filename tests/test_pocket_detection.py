def test_detect_auto_pocket_table_adds_external_evidence_guided_route():
    external_site_df = pd.DataFrame(
        [
            {
                "chain": "A",
                "resid": 1,
                "evidence_source": "Literature+Structure",
                "evidence_type": "Catalytic residue",
                "evidence_score": 1.0,
                "evidence_note": "paper active site",
                "uniprot_resid": 1,
                "mapping_level": "exact",
                "mapping_confidence": 0.9,
                "mapping_method": "literature-structure-numbering",
            }
        ]
    )

    pocket_df = detect_auto_pocket_table(
        PDB_TEXT,
        prefer_kvfinder=False,
        prefer_ligand=False,
        external_site_df=external_site_df,
    )
    diagnostics = build_pocket_detection_diagnostics_table(pocket_df)

    assert not pocket_df.empty
    assert "external-evidence" in set(diagnostics["method"].astype(str))
    assert diagnostics.loc[diagnostics["method"].astype(str) == "external-evidence", "status"].iloc[0] == "used"
    assert pocket_df["consensus_methods"].astype(str).str.contains("external-evidence").any()
    summary = summarize_pocket_detection_metadata(get_pocket_detection_metadata(pocket_df))
    assert summary["auto_detection_external_route_status"] == "used"
    assert summary["auto_detection_external_route_min_support"] == 0.58
    residue_view = pocket_df[(pocket_df["chain"].astype(str) == "A") & (pocket_df["resid"].astype(int) == 1)]
    assert not residue_view.empty
    assert residue_view["detection_route"].astype(str).str.contains("external-evidence|consensus", regex=True).any()
    assert residue_view["external_direct_anchor"].astype(bool).any()
    assert residue_view["evidence_route_anchor"].astype(bool).any()
    assert pd.to_numeric(residue_view["evidence_anchor_distance"], errors="coerce").min() == 0.0
    assert "A:1" in str(residue_view.iloc[0]["evidence_anchor_residue"])
    pocket_summary = build_pocket_summary(pocket_df, pd.DataFrame())
    assert pocket_summary["external_direct_anchor_count"].astype(int).ge(1).any()
    assert pocket_summary["evidence_route_anchor_count"].astype(int).ge(1).any()
    assert "A:1" in str(pocket_summary.iloc[0]["evidence_anchor_residues"])



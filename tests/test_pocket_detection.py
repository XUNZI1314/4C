    assert layer_by_resid[2] == "shell"
    assert layer_by_resid[3] == "rim"
    assert layer_by_resid[4] == ""
    assert color_by_resid[1] == "#991b1b"
    assert color_by_resid[2] == "#2563eb"
    assert color_by_resid[3] == "#14b8a6"
    assert "core" in label_by_resid[1]


